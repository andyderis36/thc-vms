package domain

import (
	"context"
	"strings"
	"time"
)

// This file owns the mail delivery log contract (migration 000030): the
// observability trail of the async SMTP worker in
// internal/infrastructure/mailer. Every mailer.Send call produces exactly one
// row, written at the single flush point (enqueue inserts the queued row, the
// worker upserts the sent/failed verdict). The table is never read by any
// send path: it only feeds the super_admin read endpoints
// GET /settings/mail-logs. No audit row exists for these reads (a read-only
// back-office probe, same as GET /settings/system).

// MailLogStatus is the closed verdict vocabulary of one mail_log row.
type MailLogStatus string

const (
	// MailLogQueued means the send was accepted into the worker queue and no
	// verdict has been recorded yet.
	MailLogQueued MailLogStatus = "queued"
	// MailLogSent means the final flush attempt succeeded.
	MailLogSent MailLogStatus = "sent"
	// MailLogFailed means every attempt failed (permanent refusal or the
	// transient retry budget is exhausted).
	MailLogFailed MailLogStatus = "failed"
)

// ParseMailLogStatus maps the ?status= query value onto the vocabulary.
// Empty means unfiltered (never an error); anything outside the three values
// is refused so a typo can never silently widen the listing.
func ParseMailLogStatus(raw string) (MailLogStatus, bool) {
	switch MailLogStatus(strings.TrimSpace(raw)) {
	case "":
		return "", true
	case MailLogQueued:
		return MailLogQueued, true
	case MailLogSent:
		return MailLogSent, true
	case MailLogFailed:
		return MailLogFailed, true
	default:
		return "", false
	}
}

// MailLog is one stored delivery verdict: the recipients the worker flushed
// to, the lifecycle template label when the send went through the templated
// fan-out ("" for direct sends such as the test-mail probe), the attempt
// count actually performed, and the final error text (nil unless failed).
// TextBody carries the plain-text diagnosis copy; the HTML copy is
// deliberately not stored (see the migration header).
type MailLog struct {
	ID         UUID
	Recipients []string
	// Bcc holds the hidden overseer addresses (national super_admin incl.
	// the dev-superadmin) flushed on the same send. Stored for the
	// back-office trail; never rendered into the message headers visible
	// to the To recipients.
	Bcc       []string
	Subject   string
	Template  string
	Status    MailLogStatus
	Attempts  int
	Error     *string
	TextBody  *string
	CreatedAt time.Time
	SentAt    *time.Time
}

// Pagination contract for the mail-log feed (docs/4. openapi.yaml style:
// default page size 20, maximum 100 — the notification-feed contract, not
// the audit-trail one whose default is 50). These are the ONE source of
// truth shared by the handler (which clamps caller input) and the repository
// (which re-applies the same bounds as its final defensive fallback).
const (
	// DefaultMailLogPageSize is the page size when the caller supplies no
	// limit (or one outside the accepted range).
	DefaultMailLogPageSize = 20
	// MaxMailLogPageSize caps a single mail-log page.
	MaxMailLogPageSize = 100
)

// MailLogFilter scopes a mail-log listing. Status nil means unfiltered;
// Page/Limit arrive already clamped by the handler.
type MailLogFilter struct {
	Status *MailLogStatus
	Page   int
	Limit  int
}

// NormaliseMailLogFilter applies the Limit default, floors Offset-style
// invalid pages to 1 and caps the page size, mirroring the notification
// listing contract (default 20, max 100).
func NormaliseMailLogFilter(filter MailLogFilter) MailLogFilter {
	if filter.Page < 1 {
		filter.Page = 1
	}
	if filter.Limit < 1 {
		filter.Limit = DefaultMailLogPageSize
	}
	if filter.Limit > MaxMailLogPageSize {
		filter.Limit = MaxMailLogPageSize
	}
	return filter
}

// MailLogWriter is the narrow write port the SMTP worker flushes verdicts
// through. It is separate from the read half so the mailer (a send-path
// dependency) never imports listing concerns. Both writes are best-effort by
// contract: a write failure is logged and never fails a send.
//
// The two writes are order-independent: InsertQueued is a no-op when the row
// already exists, and RecordVerdict upserts the full row, so whichever wins
// a race against the other, the stored row always carries the recipients,
// the verdict and the attempt count.
type MailLogWriter interface {
	// InsertQueued records the accepted send before the first flush attempt.
	// The id is client-generated by the mailer worker correlation, so a
	// repeated insert for the same id is a no-op, never a duplicate.
	InsertQueued(ctx context.Context, entry MailLog) error
	// RecordVerdict stores the final verdict (Status sent or failed, the
	// attempts performed and, for failures, the error text) and stamps
	// sent_at. It upserts the full row: a verdict that wins the race
	// against its own queued insert still leaves complete data behind.
	RecordVerdict(ctx context.Context, verdict MailLog) error
}

// MailLogRepository is the persistence port for the mail delivery log: the
// worker write half above plus the back-office read half below.
type MailLogRepository interface {
	MailLogWriter
	List(ctx context.Context, filter MailLogFilter) (items []MailLog, total int64, err error)
	FindByID(ctx context.Context, id UUID) (MailLog, error)
}
