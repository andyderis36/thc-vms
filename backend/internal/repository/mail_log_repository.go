// mailLogRepository is the PostgreSQL adapter for domain.MailLogRepository
// (migration 000030). It uses hand-written SQL instead of the generated
// db.Querier: the table is observability-only CRUD with no join or scope
// predicate, so a new sqlc query set plus regeneration would add surface
// without adding safety. The single static ORDER BY keeps LIMIT/OFFSET
// pagination stable, mirroring the notification listing.
type mailLogRepository struct {
	pool *pgxpool.Pool
}

var _ domain.MailLogRepository = (*mailLogRepository)(nil)

// NewMailLogRepository builds the PostgreSQL-backed domain.MailLogRepository.
func NewMailLogRepository(pool *pgxpool.Pool) domain.MailLogRepository {
	return &mailLogRepository{pool: pool}
}

// InsertQueued records the accepted send. The id is client-generated by the
// mailer worker correlation, so a repeated insert for the same id is a no-op:
// the verdict upsert below may already have won the race against this row.
func (r *mailLogRepository) InsertQueued(ctx context.Context, entry domain.MailLog) error {
	id, err := fromDomainUUID(entry.ID)
	if err != nil {
		return err
	}
	var textBody *string
	if entry.TextBody != nil {
		textBody = entry.TextBody
	}
	recipients := entry.Recipients
	if recipients == nil {
		recipients = []string{}
	}
	bcc := entry.Bcc
	if bcc == nil {
		bcc = []string{}
	}
	_, err = r.pool.Exec(ctx, `INSERT INTO mail_log (id, recipients, bcc, subject, template, status, attempts, text_body)
		VALUES ($1, $2, $3, $4, $5, 'queued', 0, $6)
		ON CONFLICT (id) DO NOTHING`,
		id, recipients, bcc, entry.Subject, entry.Template, textBody)
	if err != nil {
		return MapError(err)
	}
	return nil
}

// RecordVerdict upserts the final verdict with its full row and stamps
// sent_at. Because the identity columns ride along, a verdict that wins the
// race against its own queued insert still leaves complete data behind, and
// the later queued insert is a no-op that changes nothing.
func (r *mailLogRepository) RecordVerdict(ctx context.Context, verdict domain.MailLog) error {
	id, err := fromDomainUUID(verdict.ID)
	if err != nil {
		return err
	}
	var textBody *string
	if verdict.TextBody != nil {
		textBody = verdict.TextBody
	}
	recipients := verdict.Recipients
	if recipients == nil {
		recipients = []string{}
	}
	bcc := verdict.Bcc
	if bcc == nil {
		bcc = []string{}
	}
	_, err = r.pool.Exec(ctx, `INSERT INTO mail_log (id, recipients, bcc, subject, template, status, attempts, error, text_body, sent_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, now())
		ON CONFLICT (id) DO UPDATE SET recipients = EXCLUDED.recipients, bcc = EXCLUDED.bcc, subject = EXCLUDED.subject,
			template = EXCLUDED.template, status = EXCLUDED.status, attempts = EXCLUDED.attempts,
			error = EXCLUDED.error, text_body = EXCLUDED.text_body, sent_at = now()`,
		id, recipients, bcc, verdict.Subject, verdict.Template, string(verdict.Status), verdict.Attempts, verdict.Error, textBody)
	if err != nil {
		return MapError(err)
	}
	return nil
}

// mailLogRow is the scan target of the listing/detail reads.
type mailLogRow struct {
	ID         uuid.UUID
	Recipients []string
	Bcc        []string
	Subject    string
	Template   string
	Status     string
	Attempts   int
	Error      *string
	TextBody   *string
	CreatedAt  time.Time
	SentAt     pgtype.Timestamptz
}

// mailLogFromRow projects one stored verdict row onto the domain shape.
// A zero recipients/bcc array scans as nil; each renders as an empty list.
func mailLogFromRow(row mailLogRow) domain.MailLog {
	out := domain.MailLog{
		ID:         mustDomainUUID(row.ID),
		Recipients: row.Recipients,
		Bcc:        row.Bcc,
		Subject:    row.Subject,
		Template:   row.Template,
		Status:     domain.MailLogStatus(row.Status),
		Attempts:   row.Attempts,
		CreatedAt:  row.CreatedAt,
	}
	if out.Recipients == nil {
		out.Recipients = []string{}
	}
	if out.Bcc == nil {
		out.Bcc = []string{}
	}
	if row.Error != nil {
		msg := *row.Error
		out.Error = &msg
	}
	if row.TextBody != nil {
		body := *row.TextBody
		out.TextBody = &body
	}
	out.SentAt = timePtr(row.SentAt)
	return out
}

// List serves one page of the delivery trail, newest first, with its
// companion count. The status predicate is a bound NULLable value (the audit
// FILTER INVARIANT): nil means unfiltered, never a dropped predicate.
// Pagination defaults come from NormaliseMailLogFilter.
func (r *mailLogRepository) List(ctx context.Context, filter domain.MailLogFilter) ([]domain.MailLog, int64, error) {
	filter = domain.NormaliseMailLogFilter(filter)
	var status *string
	if filter.Status != nil {
		s := string(*filter.Status)
		status = &s
	}
	offset := (filter.Page - 1) * filter.Limit
	rows, err := r.pool.Query(ctx, `SELECT id, recipients, bcc, subject, template, status, attempts, error, text_body,
			created_at, sent_at
		FROM mail_log
		WHERE ($1::text IS NULL OR status = $1::text)
		ORDER BY created_at DESC, id DESC
		LIMIT $2 OFFSET $3`, status, filter.Limit, offset)
	if err != nil {
		return nil, 0, MapError(err)
	}
	defer rows.Close()
	var out []domain.MailLog
	for rows.Next() {
		var row mailLogRow
		if err := rows.Scan(&row.ID, &row.Recipients, &row.Bcc, &row.Subject, &row.Template, &row.Status,
			&row.Attempts, &row.Error, &row.TextBody, &row.CreatedAt, &row.SentAt); err != nil {
			return nil, 0, MapError(err)
		}
		out = append(out, mailLogFromRow(row))
	}
	if err := rows.Err(); err != nil {
		return nil, 0, MapError(err)
	}
	if out == nil {
		out = []domain.MailLog{}
	}
	var total int64
	if err := r.pool.QueryRow(ctx, `SELECT count(*)::bigint FROM mail_log
		WHERE ($1::text IS NULL OR status = $1::text)`, status).Scan(&total); err != nil {
		return nil, 0, MapError(err)
	}
	return out, total, nil
}

// FindByID returns one delivery verdict. A missing id is ErrNotFound.
func (r *mailLogRepository) FindByID(ctx context.Context, id domain.UUID) (domain.MailLog, error) {
	parsed, err := fromDomainUUID(id)
	if err != nil {
		return domain.MailLog{}, err
	}
	var row mailLogRow
	err = r.pool.QueryRow(ctx, `SELECT id, recipients, bcc, subject, template, status, attempts, error, text_body,
			created_at, sent_at
		FROM mail_log WHERE id = $1`, parsed).Scan(
		&row.ID, &row.Recipients, &row.Bcc, &row.Subject, &row.Template, &row.Status,
		&row.Attempts, &row.Error, &row.TextBody, &row.CreatedAt, &row.SentAt)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return domain.MailLog{}, domain.NotFoundEntity("Log email")
		}
		return domain.MailLog{}, MapError(err)
	}
	return mailLogFromRow(row), nil
}
